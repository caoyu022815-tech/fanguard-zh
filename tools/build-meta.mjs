const table = { race: new Map(), type: new Map(), clan: new Map() };
const bump = (kind, ko, zh) => {
  if (!ko || !zh || ko === '-' || zh === '-') return;
  if (!/[\uac00-\ud7a3]/.test(ko) || !/[\u4e00-\u9fff]/.test(zh)) return;
  if (!table[kind].has(ko)) table[kind].set(ko, new Map());
  const counter = table[kind].get(ko);
  counter.set(zh, (counter.get(zh) || 0) + 1);
};

for (const card of cards) {
  const hit = match(card);
  if (!hit) continue;
  const meta = card.cardMetadata || {};
  if (meta.races?.ko && hit.vg_race_id?.[0]) bump('race', meta.races.ko, hit.vg_race_id[0].split('/')[0]);
  for (const race of card.racesKo || []) {
    if (hit.vg_race_id?.[0]) bump('race', race, hit.vg_race_id[0].split('/')[0]);
  }
  if (meta.cardType?.ko && hit.vg_unit_id?.[0]) bump('type', meta.cardType.ko, hit.vg_unit_id[0]);
  if (meta.clanNames?.ko && hit.vg_clan_id?.[0]) bump('clan', meta.clanNames.ko, hit.vg_clan_id[0].split('/')[0]);
}

// Collab and token cards often carry several races/kinds, so pair the Korean list with the
// dump's names from the end (the leading entries are the ones the page drops).
const list = (value) =>
  String(value ?? '')
    .split('/')
    .map((x) => x.trim())
    .filter((x) => x && x !== '-');
const jpRaceToZh = new Map();
for (const record of api) {
  for (const race of record.vg_race_id || []) {
    const [zh, ja] = String(race).split('/');
    if (zh && ja && !jpRaceToZh.has(ja.trim())) jpRaceToZh.set(ja.trim(), zh.trim());
  }
}
const pairFromEnd = (koList, zhList, apply) => {
  for (let i = 1; i <= Math.min(koList.length, zhList.length); i++) {
    apply(koList[koList.length - i], zhList[zhList.length - i]);
  }
};
const GENERIC_TYPES = new Set(['普通单位', '普通指令', '触发单位', '触发指令', '设置指令', '闪现指令', 'G单位']);
for (const card of cards) {
  const meta = card.cardMetadata || {};
  const racesKo = card.racesKo || [];
  const racesJa = list(meta.races?.ja);
  const racesZh = racesJa.map((ja) => jpRaceToZh.get(ja)).filter(Boolean);
  if (racesKo.length && racesZh.length) pairFromEnd(racesKo, racesZh, (ko, zh) => bump('race', ko, zh));

  const kindsKo = meta.orderKindNames?.ko || [];
  const hit = match(card);
  const kindsZh = (hit?.vg_unit_id || []).filter((zh) => !GENERIC_TYPES.has(zh));
  if (kindsKo.length && kindsZh.length) pairFromEnd(kindsKo, kindsZh, (ko, zh) => bump('type', ko, zh));
}

const pick = (kind) => {
  const out = {};
  for (const [ko, counter] of table[kind]) out[ko] = [...counter.entries()].sort((a, b) => b[1] - a[1])[0][0];
  return out;
};

